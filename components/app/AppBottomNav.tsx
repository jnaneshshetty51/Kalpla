export function AppBottomNav() {
  const pathname = usePathname();

  // Hide bottom nav on workspace pages and live-session video rooms to
  // grant full height to the code canvas / call UI respectively.
  if (pathname?.startsWith("/workspace/") || pathname?.match(/^\/live-sessions\/[^/]+\/room$/)) {
    return null;
  }

  return (
    <nav className="md:hidden fixed bottom-0 left-0 right-0 z-40 bg-observatory-panel/95 backdrop-blur-md border-t border-steel-800 px-4 py-2">
      <div className="flex items-center justify-around">
        {NAV_ITEMS.map((item) => {
          const isActive = pathname === item.href || (item.href !== "/dashboard" && pathname.startsWith(item.href));

          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex flex-col items-center gap-1 transition text-xs font-mono ${
                isActive
                  ? "text-telemetry-cyan font-bold"
                  : "text-steel-400 hover:text-steel-200"
              }`}
            >
              <div className={`p-1 rounded-xl transition ${isActive ? "bg-telemetry-cyan/10" : ""}`}>
                {item.icon}
              </div>
              <span className="text-[10px]">{item.label}</span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
